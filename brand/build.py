# ---------------------------------------------------------------- stationery
def build_stationery():
    print("stationery ...")
    S = OUT / "stationery"
    P = OUT / "previews"
    for d in (S, P):                      # start clean so no stale files from earlier designs remain
        shutil.rmtree(d, ignore_errors=True)

    # (file stem, html factory, sides, trim size, preview scale)
    items = [
        ("business-card", st.business_card_doc, ("front", "back"), (st.CARD_W, st.CARD_H), 6),
        ("envelope-dl", st.envelope_dl_doc, ("to", "front"), (st.ENV_W, st.ENV_H), 3),
        ("envelope-a4", st.envelope_a4_doc, ("to", "front"), (st.A4_W, st.A4_H), 1.6),
        ("file-cover", st.file_cover_doc, ("front", "inside"), (st.FILE_W, st.FILE_H), 1.6),
    ]
    for stem, factory, sides, trim, scale in items:
        size = st.page_size(*trim)
        f = BUILD / f"{stem}.html"
        write(f, factory())
        render.to_pdf(f, S / f"{stem}_print-bleed3mm.pdf")
        for side in sides:
            fp = BUILD / f"{stem}_{side}.html"
            write(fp, factory((side,)))
            render.to_png(fp, P / f"{stem}_{side}.png", size[0], size[1], scale)

    # letterhead: blank print file (no bleed, white) + specimen letter
    f = BUILD / "letterhead.html"
    write(f, st.letterhead_doc(False, False))
    render.to_pdf(f, S / "letterhead-a4_print.pdf")
    f2 = BUILD / "letterhead_prev.html"
    write(f2, st.letterhead_doc(False, True))
    render.to_png(f2, P / "letterhead-a4.png", st.A4_W, st.A4_H, 2)
    f3 = BUILD / "letterhead_specimen.html"
    write(f3, st.letterhead_doc(True, True))
    render.to_png(f3, P / "letterhead-a4_specimen.png", st.A4_W, st.A4_H, 2)
    render.to_pdf(f3, S / "letterhead-a4_specimen.pdf")

    write(S / "qr" / "qr_website.svg", st.qr_svg(FIRM["url"]).replace("<svg ", '<svg xmlns="http://www.w3.org/2000/svg" ', 1))
    print("  done")


