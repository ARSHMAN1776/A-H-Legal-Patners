def ensure_fonts():
    """Copy the font files the templates reference from node_modules (run `npm install` first)."""
    fonts = BUILD / "fonts"
    fonts.mkdir(parents=True, exist_ok=True)
    nm = ROOT / "node_modules"
    wanted = [
        *(nm / "@fontsource/cormorant-garamond/files" / f"cormorant-garamond-latin-{w}-{s}.woff2"
          for w in (300, 400, 500, 600) for s in ("normal", "italic")),
        nm / "@fontsource-variable/geist/files/geist-latin-wght-normal.woff2",
        nm / "@fontsource/noto-nastaliq-urdu/files/noto-nastaliq-urdu-arabic-400-normal.woff2",
    ]
    for src in wanted:
        if not src.exists():
            raise SystemExit(f"Missing font {src.name}. Run `npm install` in the project folder first.")
        dst = fonts / src.name
        if not dst.exists():
            shutil.copy(src, dst)


def main():
    target = sys.argv[1] if len(sys.argv) > 1 else "all"
    BUILD.mkdir(exist_ok=True)
    ensure_fonts()
    if target in ("all", "logos"):
        build_logos()
    if target in ("all", "web"):
        build_web()
    if target in ("all", "stationery"):
        build_stationery()
    if target in ("all", "social"):
        build_social()
    if target in ("all", "guidelines"):
        build_guidelines()
    print("finished ->", OUT)


if __name__ == "__main__":
    main()
