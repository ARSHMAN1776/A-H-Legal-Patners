def write(path: Path, text: str):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def viewbox(svg: str) -> tuple[float, float, float, float]:
    m = re.search(r'viewBox="([-\d.\s]+)"', svg)
    return tuple(float(v) for v in m.group(1).split())  # type: ignore[return-value]


# --------------------------------------------------------------------- logos
def build_logos():
    print("logos ...")
    variants = {
        "seal": lambda cw, bg: logo.seal_svg(cw, "line", bg=bg, pad=24),
        "lockup-horizontal": lambda cw, bg: logo.lockup_horizontal(cw, bg=bg, pad=30),
        "wordmark": lambda cw, bg: logo.wordmark_svg(cw, bg=bg, pad=30),
        "symbol": lambda cw, bg: logo.symbol_svg(cw, bg=bg, pad=24),
    }
    for name, fn in variants.items():
        for cw in logo.COLORWAYS:
            tile = cw in ("on-dark", "on-paper")   # these two ship on their own background
            svg = fn(cw, tile)
            stem = f"ah-{name}_{cw}"
            write(OUT / "logo" / "svg" / f"{stem}.svg", svg)
            _, _, w, h = viewbox(svg)
            px_w = 2400
            px_h = round(px_w * h / w)
            html = BUILD / f"_logo_{stem}.html"
            svg_sized = svg.replace("<svg ", f'<svg width="{px_w}" height="{px_h}" ', 1)
            write(html, f"<!doctype html><meta charset=utf-8><body style='margin:0;background:transparent'>{svg_sized}")
            render.to_png_px(html, OUT / "logo" / "png" / f"{stem}.png", px_w, px_h, 1, transparent=not tile)
            html.unlink()
    write(OUT / "logo" / "svg" / "ah-favicon.svg", logo.favicon_svg())
    print("  done")


